/** Run only after the owner confirms a stable, complete backend build. Node >=22. */
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { tmpdir } from 'node:os';

const root = resolve(process.cwd());
const cli = join(root, 'backend/dist/cli.js');
const out = process.argv[2];
if (!out || !resolve(out).startsWith(resolve(tmpdir()) + '/')) throw new Error('Provide a fresh absolute directory under the system temporary directory');
const base = resolve(out);
if (existsSync(base)) throw new Error('Output directory already exists');
const built = readFileSync(cli, 'utf8');
if (!built.includes('catalogueCorpus') || !existsSync(join(root, 'backend/dist/io/catalogue-output.js'))) throw new Error('BLOCKED: compiled CLI lacks catalogue integration; owner must complete build');
mkdirSync(base, { recursive: true });
const state = join(base, 'state'), workspace = join(base, 'workspace');
mkdirSync(state); mkdirSync(workspace);
const env = { ...process.env, CLEC_WORKSPACE: root, CLEC_STATE_DIR: state, CLEC_QMD_URL: 'http://localhost:18181' };
delete env.DEEPSEEK_API_KEY;
const start = new Date().toISOString();
const command = ['catalogue', '--root', root, '--manifest', join(state, 'full-intake.json'), '--report', join(state, 'catalogue.json')];
const result = spawnSync(process.execPath, [cli, ...command], { env, encoding: 'utf8', maxBuffer: 16 * 1024 * 1024 });
writeFileSync(join(base, 'catalogue.stdout'), result.stdout ?? '');
writeFileSync(join(base, 'catalogue.stderr'), result.stderr ?? '');
if (result.status !== 0) throw new Error(`Catalogue failed with status ${result.status}; see isolated logs`);
const full = JSON.parse(readFileSync(join(state, 'full-intake.json'), 'utf8'));
const ids = ['CLEC-002', 'CLEC-011', 'CLEC-031', 'CLEC-038'];
const cases = readFileSync(join(root, 'evaluation/backend-e2e/development.jsonl'), 'utf8').trim().split('\n').map(line => JSON.parse(line)).filter(c => ids.includes(c.id));
const paths = [...new Set([...cases.flatMap(c => c.evidence.map((e: {path:string}) => e.path)), 'collection/web/clectw/transcripts/short-00575.txt'])] as string[];
const sources = paths.map(path => {
  const source = full.sources.find((s: {path:string;status:string}) => s.path === path && s.status === 'ready');
  if (!source) throw new Error(`Selected source is absent or not ready: ${path}`);
  const original = join(root, path), copy = join(workspace, path);
  mkdirSync(dirname(copy), { recursive: true }); cpSync(original, copy);
  const sha = (file: string) => createHash('sha256').update(readFileSync(file)).digest('hex');
  const originalHash = sha(original), copyHash = sha(copy);
  if (originalHash !== copyHash) throw new Error(`Copy mismatch: ${path}`);
  for (const c of cases) for (const e of c.evidence) if (e.path === path && e.sha256 !== originalHash) throw new Error(`Development hash mismatch: ${path}`);
  return { source, originalHash, copyHash };
});
writeFileSync(join(base, 'intake.json'), JSON.stringify({ schemaVersion: 1, sources: sources.map(s => s.source) }, null, 2));
writeFileSync(join(base, 'selection.json'), JSON.stringify({ start, end: new Date().toISOString(), ids, sources, cliSha256: createHash('sha256').update(built).digest('hex'), catalogueCommand: [process.execPath, cli, ...command] }, null, 2));
console.log(`Prepared real-source copy and catalogue in ${base}; no build or provider request was made.`);
